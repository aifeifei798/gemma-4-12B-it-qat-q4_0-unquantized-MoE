export function coreName(raw, lang, i) {
  if (lang === 'en') {
    const m = /[A-Za-z_]+$/.exec(raw || '')
    return m ? `${i}·${m[0]}` : `${i}·${CORE_EN[i] || ''}`
  }
  return `${i}·${raw}`
}

